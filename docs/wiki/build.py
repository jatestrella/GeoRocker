SHOT_OF = {"research": "npc_mechanic"}

def page():
	here = os.path.dirname(os.path.abspath(__file__))
	def icon(iid):
		return f"img/{iid}.png" if os.path.exists(os.path.join(here, "img", iid + ".png")) else None
	def shot(iid):
		sid = SHOT_OF.get(iid, iid)
		return f"shots/{sid}.jpg" if os.path.exists(os.path.join(here, "shots", sid + ".jpg")) else None
	def thumb(iid):
		return icon(iid) or shot(iid)
	cat_name = dict(CATEGORIES)
	# 側欄
	nav = ['<a href="#home"><b>首頁</b></a>', '<div class="navh">機制</div>']
	for g, gn in MECH_GROUPS:
		for m in MECHANICS:
			if m[2] == g: nav.append(f'<a href="#{m[0]}">{E(m[1])}</a>')
	nav.append('<div class="navh">元件</div>')
	nav += [f'<a href="#c-{c}">{E(n)}</a>' for c, n in CATEGORIES]
	pages = []
	# 首頁
	home = ['<h1>GeoRocker 遊戲說明</h1>',
		'<p>岩石力學、隧道、大地工程的採礦模擬。左邊選機制或元件分類，或用上方的搜尋。</p>', '<h2>機制</h2>']
	for g, gn in MECH_GROUPS:
		links = " ".join(f'<a class="mlink" href="#{m[0]}">{E(m[1])}</a>' for m in MECHANICS if m[2] == g)
		home.append(f'<p><span class="grp">{E(gn)}</span>{links}</p>')
	for c, n in CATEGORIES:
		tiles = []
		for it in ITEMS:
			if it[2] != c: continue
			t = thumb(it[0])
			img = f'<img src="{t}" alt="" loading="lazy">' if t else '<span class="noimg"></span>'
			tiles.append(f'<a class="tile" href="#i-{it[0]}">{img}<span>{E(it[1])}</span></a>')
		home.append(f'<h2 id="h-{c}">{E(n)}</h2><div class="tiles">{"".join(tiles)}</div>')
	pages.append(f'<article class="page" id="home">{"".join(home)}</article>')
	# 分類頁
	for c, n in CATEGORIES:
		tiles = []
		for it in ITEMS:
			if it[2] != c: continue
			t = thumb(it[0])
			img = f'<img src="{t}" alt="" loading="lazy">' if t else '<span class="noimg"></span>'
			tiles.append(f'<a class="tile" href="#i-{it[0]}">{img}<span>{E(it[1])}</span></a>')
		pages.append(f'<article class="page" id="c-{c}"><p class="crumb"><a href="#home">首頁</a> › 元件</p><h1>{E(n)}</h1><div class="tiles">{"".join(tiles)}</div></article>')
	# 機制頁
	gname = dict(MECH_GROUPS)
	for mid, title, g, content in MECHANICS:
		pages.append(f'<article class="page mech" id="{mid}"><p class="crumb"><a href="#home">首頁</a> › 機制 › {E(gname[g])}</p><h1>{E(title)}</h1>{content}</article>')
	# 元件頁
	for iid, name, c, get, use, note in ITEMS:
		ic, sh = icon(iid), shot(iid)
		box = [f'<div class="ibox-title">{E(name)}</div>']
		if sh: box.append(f'<img class="ibox-shot" src="{sh}" alt="{E(name)}（遊戲內）" loading="lazy"><div class="cap">遊戲內</div>')
		if ic: box.append(f'<img class="ibox-icon" src="{ic}" alt="" loading="lazy"><div class="cap">圖示</div>')
		box.append(f'<table><tr><th>分類</th><td><a href="#c-{c}">{E(cat_name[c])}</a></td></tr><tr><th>取得</th><td>{E(get)}</td></tr></table>')
		body = [f'<p class="crumb"><a href="#home">首頁</a> › <a href="#c-{c}">{E(cat_name[c])}</a></p>', f'<h1>{E(name)}</h1>',
			f'<aside class="ibox">{"".join(box)}</aside>', f'<h2>操作</h2><p>{E(use)}</p>']
		if note: body.append(f'<h2>說明</h2><div>{note}</div>')
		text = re.sub(r"<[^>]+>", " ", name + " " + get + " " + use + " " + note)
		pages.append(f'<article class="page item" id="i-{iid}" data-text="{E(text)}" data-title="{E(name)}">{"".join(body)}</article>')
	tpl = open(os.path.join(here, "template.html"), encoding="utf-8").read()
	return tpl.replace("{{NAV}}", "\n".join(nav)).replace("{{BODY}}", "\n".join(pages))

